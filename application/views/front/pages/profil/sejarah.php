	   Pertahanan dari sudut pandang militer, politik, ekonomi, sosial dan budaya.

Sejarah Unhan berawal dari salah satu program kursus di Sekolah Komando Angkatan Darat (Seskoad). 
Tahun 2006, Panglima TNI Jenderal TNI Djoko Santoso, pada saat masih menjabat Kepala Staf Angkatan Darat (KSAD)
menugaskan Komandan Seskoad Mayjen TNI Syarifudin Tippe untuk membuat Kursus Strategi Perang Semesta di Seskoad.
Kursus inilah yang menjadi cikal bakal perwujudan ide untuk mendirikan sebuah perguruan tinggi yang mempelajari studi pertahanan. 
Gagasan untuk memiliki perguruan tinggi di bidang pertahanan juga dimiliki oleh Presiden SBY selagi beliau masih aktif di militer, 
sehingga pendirian Unhan disambut dengan baik dan didukung oleh Presiden SBY. Menteri Pertahanan dalam Kabinet Indonesia Bersatu I,
Profesor Juwono Sudarsono termasuk salah tokoh yang ikut membidani lahirnya Unhan.

Unhan merupakan lembaga pendidikan tinggi yang memberi kesempatan bagi para perwira TNI dan masyarakat umum untuk belajar 
dan memperdalam Ilmu Pertahanan pada tingkat Sarjana/Strata-1, magister/Strata-2 dan Doktoral/Strata-3. Unhan dicita-citakan
menjadi universitas kelas dunia. Beberapa universitas luar negeri seperti Cranfield University, National Defense University Amerika Serikat,
Rajaratnam School of International Studies Singapura dan beberapa universitas di Australia dan Jerman juga turut aktif mendukung pendirian dan 
berjalannya proses belajar mengajar di Unhan. Kerjasama diberikan dalam bentuk pengiriman tenaga pengajar, kurikulum, beasiswa dan studi banding.
Universitas di dalam negeri seperti UI dan ITB juga aktif mendukung Unhan dengan mengirim sejumlah guru besarnya untuk membantu membangun dan menjalankan
proses belajar mengajar di Unhan.
